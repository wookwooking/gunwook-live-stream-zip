(()=>{'use strict';
  if(!window.matchMedia('(pointer:fine)').matches||window.matchMedia('(prefers-reduced-motion:reduce)').matches)return;
  const colors=['#ff80ae','#f5a1c1','#ffb7d2','#e96b9d','#ffc8dc'];
  let last=0;const active=new Set(),limit=130;
  function heart(x,y,burst=false,index=0,total=1){if(active.size>=limit)return;
    const p=document.createElement('span');p.className='cursor-particle';p.setAttribute('aria-hidden','true');p.textContent=Math.random()<.25?'♡':'♥';
    const angle=burst?(index/total)*Math.PI*2+(Math.random()-.5)*.25:Math.random()*Math.PI*2;
    const radius=burst?38+Math.random()*95:12+Math.random()*20;
    const dx=burst?Math.cos(angle)*radius:(Math.random()-.5)*35;
    const dy=burst?Math.sin(angle)*radius:-15-Math.random()*30;
    p.style.left=x+'px';p.style.top=y+'px';p.style.fontSize=(burst?12+Math.random()*14:9+Math.random()*9)+'px';
    p.style.setProperty('--dx',dx+'px');p.style.setProperty('--dy',dy+'px');
    p.style.setProperty('--spin',(Math.random()*100-50)+'deg');
    p.style.setProperty('--spark',colors[Math.floor(Math.random()*colors.length)]);
    p.style.setProperty('--life',(burst?700:650)+Math.random()*380+'ms');
    document.body.append(p);active.add(p);
    p.addEventListener('animationend',()=>{p.remove();active.delete(p)},{once:true});
  }
  document.addEventListener('pointermove',e=>{if(e.pointerType!=='mouse')return;const now=performance.now();if(now-last<35)return;last=now;heart(e.clientX+8,e.clientY+9)},{passive:true});
  document.addEventListener('pointerdown',e=>{if(e.pointerType!=='mouse')return;const count=24;for(let i=0;i<count;i++)heart(e.clientX,e.clientY,true,i,count)},{passive:true});
})();
